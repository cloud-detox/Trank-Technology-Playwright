def add(a,b):
    print("Addition : ", a+b)
def sub(a,b):
    print("Subtraction : ", a-b)
def mul(a,b):
    print("Multiplation : ", a*b)
def div(a,b):
    print("Division : ", a/b)
def rem(a,b):
    print("Remainder : ", a%b)
def fdiv(a,b):
    print("Floor Division : ", a//b)
def exp(a,b):
    print("Exponential : ", a**b)

def cal(a,b):
    add(a,b)
    sub(a,b)
    mul(a,b)
    div(a,b)
    rem(a,b)
    fdiv(a,b)
    exp(a,b)

cal(2,4)